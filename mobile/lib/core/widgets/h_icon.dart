  /// Есть ли у Material-иконки пара в Hugeicons.
  static bool has(IconData icon) => _map.containsKey(icon);

  @override
  Widget build(BuildContext context) {
    final theme = IconTheme.of(context);
    final c = color ?? theme.color ?? Colors.black;
    final s = size ?? theme.size ?? 24.0;
    final data = icon == null ? null : _map[icon];
    if (data == null) {
      return Icon(icon, color: c, size: s, semanticLabel: semanticLabel, shadows: shadows);
    }
    // Как у Material Icon: снаружи квадрат size×size, внутри по центру сама
    // иконка того же размера. Без этого в жёсткой рамке (кнопка 40×40,
    // prefixIcon поля) HugeIcon растягивался на всю рамку.
    final child = SizedBox(
      width: s,
      height: s,
      child: Center(
        child: SizedBox(width: s, height: s, child: HugeIcon(icon: data, color: c, size: s, strokeWidth: 1.6)),
      ),
    );
    if (semanticLabel == null) return ExcludeSemantics(child: child);
    return Semantics(label: semanticLabel, child: child);
  }
